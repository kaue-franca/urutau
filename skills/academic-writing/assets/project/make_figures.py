# Why: regenerate every figure and every number of the paper and the talk from the saved results, so each claim's evidence traces to this script.
"""Build figures/paper/*.pdf, figures/talk/*.pdf and numbers.tex from data/example.csv (example content: replace it)."""
import csv
import statistics
from pathlib import Path

import matplotlib

matplotlib.use("pgf")  # labels typeset by LuaLaTeX, so figure text matches the document
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).parent
STYLES = {"paper": "urutau-paper.mplstyle", "talk": "urutau-slides.mplstyle"}


def load(path):
    """Read the scores per method and run from the CSV."""
    scores = {}
    with open(path, newline="") as f:
        for r in csv.DictReader(f):
            scores.setdefault(r["method"], {})[int(r["run"])] = float(r["score"])
    return scores


def write_numbers(macros, path):
    """Write the numbers the text cites as LaTeX macros, so the text never drifts from the outputs."""
    lines = [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in macros.items()]
    path.write_text("% Generated by make_figures.py: do not edit.\n" + "\n".join(lines) + "\n")


def fig_runs(scores, out):
    """Plot every run of each method as a dot and its mean as a bar mark: the spread stays visible."""
    fig, ax = plt.subplots()
    for y, (method, color) in enumerate([("baseline", "#8A8F98"), ("new", "#C2410C")]):
        values = list(scores[method].values())
        ax.scatter(values, [y] * len(values), color=color, s=18, zorder=3)
        ax.plot([statistics.mean(values)] * 2, [y - 0.25, y + 0.25], color=color, linewidth=2)
    ax.set_yticks([0, 1], ["Baseline", "New method"])
    ax.set_ylim(-0.6, 1.6)
    ax.set_xlabel("Score per run (dots) and mean (bar)")
    fig.savefig(out)
    plt.close(fig)


def main():
    """Run every figure in both styles and write numbers.tex."""
    scores = load(HERE / "data" / "example.csv")
    for kind, style in STYLES.items():
        with plt.style.context(HERE / style):
            (HERE / "figures" / kind).mkdir(parents=True, exist_ok=True)
            fig_runs(scores, HERE / "figures" / kind / "runs.pdf")
    runs = sorted(scores["baseline"])
    gains = [scores["new"][r] - scores["baseline"][r] for r in runs]  # paired by run
    write_numbers({
        "nRuns": str(len(runs)),
        "baselineMean": f"\\num{{{statistics.mean(scores['baseline'].values()):.3f}}}",
        "newMean": f"\\num{{{statistics.mean(scores['new'].values()):.3f}}}",
        "gainMean": f"\\num{{{statistics.mean(gains):.3f}}}",
        "gainMin": f"\\num{{{min(gains):.3f}}}",
        "gainMax": f"\\num{{{max(gains):.3f}}}",
    }, HERE / "numbers.tex")


if __name__ == "__main__":
    main()

# Why: regenerate every figure and every number the deck shows from the saved data, so each one is traceable to this script.
"""Build figures/*.pdf and numbers.tex for the deck from data/example.csv (example content: replace it)."""
import csv
from pathlib import Path

import matplotlib

matplotlib.use("pgf")  # labels typeset by LuaLaTeX, so figure text matches the slides
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).parent
CHANGE_MONTH = "2026-06"  # first month after the change (example)


def load(path):
    """Read the (month, value) series from the CSV."""
    with open(path, newline="") as f:
        return [(r["month"], float(r["value"])) for r in csv.DictReader(f)]


def write_numbers(macros, path):
    """Write the numbers the slides cite as LaTeX macros, so the text never drifts from the outputs."""
    lines = [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in macros.items()]
    path.write_text("% Generated by make_figures.py: do not edit.\n" + "\n".join(lines) + "\n")


def fig_trend(rows, out):
    """Plot the series: grey before the change, the accent color after it, labels on the lines."""
    months = [m for m, _ in rows]
    values = [v for _, v in rows]
    cut = months.index(CHANGE_MONTH)
    fig, ax = plt.subplots()
    ax.plot(range(cut), values[:cut], color="#8A8F98")
    ax.plot(range(cut - 1, len(months)), values[cut - 1:], color="#C2410C")
    ax.set_xticks(range(len(months)), [m[5:] + "/" + m[2:4] for m in months])
    ax.set_ylabel("Monthly churn (\\%)")
    ax.set_ylim(0, max(values) * 1.15)  # honest baseline: the axis starts at zero
    ax.annotate("after the change", (len(months) - 1, values[-1]), xytext=(0, 8),
                textcoords="offset points", ha="right", color="#C2410C")
    fig.savefig(out)
    plt.close(fig)


def main():
    """Run every figure and write numbers.tex."""
    plt.style.use(HERE / "urutau-slides.mplstyle")
    rows = load(HERE / "data" / "example.csv")
    (HERE / "figures").mkdir(exist_ok=True)
    fig_trend(rows, HERE / "figures" / "trend.pdf")
    months = [m for m, _ in rows]
    cut = months.index(CHANGE_MONTH)
    before = sum(v for _, v in rows[:cut]) / cut
    after = sum(v for _, v in rows[cut:]) / (len(rows) - cut)
    write_numbers({
        "valueBefore": f"\\qty{{{before:.1f}}}{{\\percent}}",
        "valueAfter": f"\\qty{{{after:.1f}}}{{\\percent}}",
        "valueDrop": f"\\qty{{{100 * (before - after) / before:.0f}}}{{\\percent}}",
    }, HERE / "numbers.tex")


if __name__ == "__main__":
    main()
